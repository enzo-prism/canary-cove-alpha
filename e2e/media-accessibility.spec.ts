import { expect, test } from "@playwright/test"

import { expectTapTarget, waitForPageReady } from "./helpers"

test.describe("media controls and responsive accessibility", () => {
  test("estate spaces expose one operable slide and keyboard navigation updates it", async ({ page, browserName }) => {
    await page.goto("/")
    await waitForPageReady(page)
    const carousel = page.getByTestId("model-carousel-viewport")
    await carousel.scrollIntoViewIfNeeded()
    await expect(carousel.getByRole("link")).toHaveCount(1)
    await expect(page.getByTestId("model-slide-1")).toHaveAttribute("inert", "")
    await carousel.focus()
    // Safari's native page-link traversal uses Option+Tab by default. The
    // carousel keeps native page order rather than overriding that preference.
    await page.keyboard.press(browserName === "webkit" ? "Alt+Tab" : "Tab")
    await expect(page.getByTestId("model-cta-0")).toBeFocused()
    await page.keyboard.press(browserName === "webkit" ? "Alt+Tab" : "Tab")
    await expect(page.getByRole("button", { name: "Go to Main Villa", exact: true })).toBeFocused()
    const next = page.getByRole("button", { name: "Go to King Suites", exact: true })
    await expectTapTarget(next)
    await next.click()
    await expect(page.getByTestId("model-slide-0")).toHaveAttribute("inert", "")
    await expect(page.getByTestId("model-slide-1")).not.toHaveAttribute("inert", "")
    await expect(carousel.getByRole("link", { name: "See suites" })).toHaveCount(1)
    await expect(page.getByRole("status").filter({ hasText: "King Suites, space 2 of" })).toBeVisible()
  })

  test("photo carousels hide off-screen buttons while retaining the visible preview", async ({ page }) => {
    await page.goto("/stay")
    await waitForPageReady(page)
    const tour = page.getByTestId("stay-mini-gallery").getByRole("region", { name: "Stay photo tour" })
    await tour.scrollIntoViewIfNeeded()
    const slides = tour.locator('[aria-roledescription="slide"]')
    await expect(slides.nth(2)).toHaveAttribute("inert", "")
    await expect(tour.getByRole("button", { name: /^View photo:/ })).toHaveCount(2)
    await expect(slides.nth(1)).not.toHaveAttribute("inert", "")
    await page.getByTestId("stay-mini-gallery").getByRole("button", { name: "Next photo", exact: true }).click()
    await expect(slides.nth(1)).not.toHaveAttribute("inert", "")

    await page.goto("/book")
    await waitForPageReady(page)
    const bookingPhotos = page.locator('#gallery [aria-roledescription="carousel"]')
    await bookingPhotos.scrollIntoViewIfNeeded()
    await expect(bookingPhotos.getByRole("button", { name: /^View photo:/ })).toHaveCount(1)
    await expect(bookingPhotos.locator('[aria-roledescription="slide"]').nth(1)).toHaveAttribute("inert", "")
  })

  test("small-window lightbox offers tap controls, announcements and keyboard focus return", async ({ page }) => {
    await page.setViewportSize({ width: 390, height: 844 })
    await page.goto("/stay")
    await waitForPageReady(page)
    const opener = page.locator("#inside-the-villa").getByRole("button", { name: /^View photo:/ }).first()
    await opener.scrollIntoViewIfNeeded()
    await opener.focus()
    await page.keyboard.press("Enter")
    const lightbox = page.getByTestId("photo-lightbox")
    await expect(lightbox).toBeVisible()
    const next = lightbox.getByRole("button", { name: "Next photo", exact: true })
    const previous = lightbox.getByRole("button", { name: "Previous photo", exact: true })
    await expectTapTarget(next)
    await expectTapTarget(previous)
    await expect(lightbox.getByRole("status")).toHaveText("1 / 9")
    await next.click()
    await expect(lightbox.getByRole("status")).toHaveText("2 / 9")
    await expect(lightbox.getByRole("group", { name: /^Photo \d/ })).toHaveCount(1)
    await previous.click()
    await expect(lightbox.getByRole("status")).toHaveText("1 / 9")
    await page.keyboard.press("Escape")
    await expect(lightbox).not.toBeVisible()
    await expect(opener).toBeFocused()
  })

  test("outdoor gallery falls back when a short desktop window cannot fit its content", async ({ page }) => {
    await page.setViewportSize({ width: 1280, height: 640 })
    await page.goto("/stay")
    await waitForPageReady(page)
    const outdoor = page.locator("#outside-the-villa")
    await outdoor.scrollIntoViewIfNeeded()
    await expect(outdoor).toHaveAttribute("data-pinned", "false")
    const forward = outdoor.getByRole("button", { name: "Scroll outdoor photos forward" })
    await expectTapTarget(forward)
    await forward.click()
    await expect.poll(() => outdoor.locator(".overflow-x-auto").evaluate((node) => node.scrollLeft)).toBeGreaterThan(0)

    await page.setViewportSize({ width: 1440, height: 1000 })
    await expect(outdoor).toHaveAttribute("data-pinned", "true")
    await page.emulateMedia({ reducedMotion: "reduce" })
    await expect(outdoor).toHaveAttribute("data-pinned", "false")
    await page.emulateMedia({ reducedMotion: "no-preference" })
    await expect(outdoor).toHaveAttribute("data-pinned", "true")
    await page.setViewportSize({ width: 1280, height: 640 })
    await expect(outdoor).toHaveAttribute("data-pinned", "false")
    await expect(forward).toBeVisible()
  })

  test("video transport remains operable while keyboard focus rests on its controls", async ({ page }) => {
    await page.goto("/adventures")
    await waitForPageReady(page)
    const player = page.getByTestId("reef-video-manta-ray-rollover")
    await player.scrollIntoViewIfNeeded()
    await player.getByTestId("reef-video-manta-ray-rollover-play").click()
    const pause = player.getByTestId("reef-video-manta-ray-rollover-toggle")
    await expect(pause).toHaveAttribute("aria-label", "Pause A manta rolls overhead")
    await pause.focus()
    // The previous 2.8s inactivity timer hid and made this focused bar inert.
    await page.waitForTimeout(3100)
    await expect(pause).toBeFocused()
    await expect(player.getByTestId("reef-video-manta-ray-rollover-controls")).not.toHaveAttribute("inert", "")
    await page.keyboard.press("Space")
    await expect(pause).toHaveAttribute("aria-label", "Play A manta rolls overhead")
    await expect(pause).toBeFocused()
  })
})
